#!/usr/bin/env node
// Pit Log v0.2 migration + behaviour tests (R-01).
// Usage: node tests/run-tests.js [path/to/your/pitlog-backup.json ...]
// Extra paths are treated as real v0.1 exports and get the full fixture treatment.
const fs = require('fs');
const path = require('path');
const assert = require('assert');
const C = require('../core.js');
const V1 = require('./v01-reference.js');

const typeLabel = id => id; // labels don't matter for equivalence; same function both sides
let pass = 0, fail = 0;
function test(name, fn) {
  try { fn(); pass++; console.log('  ✓', name); }
  catch (e) { fail++; console.log('  ✗', name, '\n     ', e.message.split('\n').slice(0, 6).join('\n      ')); }
}
const clone = x => JSON.parse(JSON.stringify(x));
const stripExportedAt = ({ exportedAt, ...r }) => r;

// ---- fixtures ----
const real = JSON.parse(fs.readFileSync(path.join(__dirname, 'fixtures/v1-real-shape.json'), 'utf8'));
const fixtures = { 'v1-real-shape (generated by v0.1 UI)': real };
fixtures['empty'] = { schemaVersion: 1, vehicles: [], services: [] };
fixtures['no schemaVersion + missing optional fields'] = {
  vehicles: [{ id: 'a', year: '1994', make: 'Mazda', model: 'MX-5 Miata', unit: 'mi', odometer: 154200, number: '88', color: '#f6c431' }],
  services: [
    { id: 's1', vehicleId: 'a', date: '2026-03-10', odometer: 151000, type: 'oil' },          // no parts, cost, shop, notes
    { id: 's2', vehicleId: 'a', date: '2026-05-02', odometer: '', type: 'brakes', parts: [] },
  ],
};
fixtures['unknown fields are preserved'] = {
  schemaVersion: 1, someFutureThing: { x: 1 },
  vehicles: [{ ...real.vehicles[0], vin: '1ABC', custom: [1, 2] }],
  services: [{ ...real.services[0], receipt: 'r.jpg', parts: [{ name: 'x', partNo: '', qty: 1, brand: 'Bosch' }] }],
};
for (const p of process.argv.slice(2)) fixtures[`USER FILE ${path.basename(p)}`] = JSON.parse(fs.readFileSync(p, 'utf8'));

// Expected v2 output built independently of migrate(): v1 + exactly the new defaults.
function expectedV2(v1) {
  return {
    ...v1, schemaVersion: 2,
    settings: { ...(v1.settings || {}), entitlement: (v1.settings && v1.settings.entitlement) || 'free' },
    vehicles: (v1.vehicles || []).map(v => ({ ...v, purchase: v.purchase ?? null })),
    services: (v1.services || []).map(s => ({ ...s, title: s.title ?? null, parts: (s.parts || []).map(p => ({ ...p, showOnBuild: p.showOnBuild ?? false })) })),
    buildSheet: v1.buildSheet || [], odometerLogs: v1.odometerLogs || [],
  };
}

const TODAYS = ['2026-11-18', '2026-12-31', '2027-02-15', '2027-08-01'];

for (const [name, fx] of Object.entries(fixtures)) {
  console.log(`\n${name}`);
  const input = clone(fx);
  const m = C.migrate(input);

  test('migrate(v1) equals expected v2 output exactly', () => assert.deepStrictEqual(m, expectedV2(fx)));
  test('input object is not mutated', () => assert.deepStrictEqual(input, fx));
  test('every v1 vehicle/service field survives unchanged', () => {
    fx.vehicles.forEach((v, i) => Object.keys(v).forEach(k => assert.deepStrictEqual(m.vehicles[i][k], v[k], `vehicle.${k}`)));
    fx.services.forEach((s, i) => Object.keys(s).filter(k => k !== 'parts').forEach(k => assert.deepStrictEqual(m.services[i][k], s[k], `service.${k}`)));
  });
  test('migrating an already-v2 file is a no-op', () => assert.deepStrictEqual(C.migrate(clone(m)), m));
  test('v2 export → import round-trip is identical (ignoring exportedAt)', () => {
    const file = JSON.parse(JSON.stringify(C.exportPayload(m, '2026-11-18T20:00:00.000Z')));
    assert.ok(file.exportedAt);
    const back = C.replaceData(m, C.migrate(file));
    assert.deepStrictEqual(stripExportedAt(back), m);
  });
  test('oil sticker identical before/after migration (4 dates)', () => {
    for (const t of TODAYS) for (const v of fx.vehicles) {
      const a = V1.oilStatus(fx, v, t);
      const b = C.oilStatus(m, m.vehicles.find(x => x.id === v.id), t);
      assert.deepStrictEqual(b && { ...b, lastId: b.last.id, last: undefined }, a && { ...a, last: undefined }, `${v.id} @ ${t}`);
    }
  });
  test('log sort order identical', () => {
    assert.deepStrictEqual([...m.services].sort(C.byDateDesc).map(s => s.id), [...fx.services].sort(V1.byDateDesc).map(s => s.id));
  });
  test('log filter/search results identical', () => {
    const qs = ['', 'filter', 'mobil', '90915', 'oil', 'kal', 'zzz', 'diy'];
    const vs = ['all', ...fx.vehicles.map(v => v.id)];
    const ts = ['all', ...new Set(fx.services.map(s => s.type))];
    for (const q of qs) for (const fv of vs) for (const ft of ts) {
      const a = V1.filteredServices(fx, { q, fVehicle: fv, fType: ft }, typeLabel).map(s => s.id);
      const b = C.filterServices(m, { q, vehicle: fv, type: ft }, typeLabel).map(s => s.id);
      assert.deepStrictEqual(b, a, `q=${q} v=${fv} t=${ft}`);
    }
  });
}

console.log('\nRefusals');
test('a v3 file is refused with a "newer" error', () => {
  assert.throws(() => C.migrate({ schemaVersion: 3, vehicles: [], services: [] }), e => e.code === 'newer');
});
test('non-Pit-Log JSON is refused', () => {
  assert.throws(() => C.migrate({ hello: 'world' }), e => e.code === 'invalid');
  assert.throws(() => C.migrate([1, 2]), e => e.code === 'invalid');
});

console.log('\nv0.2 features');
test('F-01 entry title from parts', () => {
  const L = id => ({ repair: 'Repair', oil: 'Oil' }[id] || id);
  assert.strictEqual(C.entryTitle({ type: 'repair', parts: [{ name: 'Pinion seal' }, { name: 'Gear oil' }, { name: 'Gasket' }] }, L), 'Pinion seal +2 more');
  assert.strictEqual(C.entryTitle({ type: 'repair', parts: [{ name: '', partNo: 'P3' }] }, L), 'P3');
  assert.strictEqual(C.entryTitle({ type: 'repair', parts: [] }, L), 'Repair');
  assert.strictEqual(C.entryTitle({ type: 'oil', parts: [{ name: 'Mobil 1' }] }, L), 'Oil');
  assert.strictEqual(C.entryTitle({ type: 'repair', title: 'Rear diff rebuild', parts: [{ name: 'x' }] }, L), 'Rear diff rebuild');
});
test('F-26 mileage buckets interpolate across months and sum to total', () => {
  const r = [{ date: '2026-01-15', odo: 1000 }, { date: '2026-03-15', odo: 1590 }];
  const b = C.mileageBuckets(r, 'month');
  assert.strictEqual(Math.round(b['2026-01']), 170); // 17 of 59 days
  assert.strictEqual(Math.round(b['2026-02']), 280); // 28 days
  assert.strictEqual(Math.round(b['2026-03']), 140); // 14 days
  assert.strictEqual(Math.round(Object.values(b).reduce((a, x) => a + x, 0)), 590);
  const y = C.mileageBuckets([{ date: '2025-12-01', odo: 0 }, { date: '2026-01-31', odo: 610 }], 'year');
  assert.strictEqual(Math.round(y['2025']), 310); assert.strictEqual(Math.round(y['2026']), 300);
});
test('F-26 backwards odometer segment is ignored', () => {
  const b = C.mileageBuckets([{ date: '2026-01-01', odo: 5000 }, { date: '2026-02-01', odo: 4000 }, { date: '2026-03-01', odo: 4280 }], 'month');
  assert.deepStrictEqual(Object.keys(b), ['2026-02']);
});
test('F-26 readings merge services, logs and purchase without duplicates', () => {
  const db = C.migrate(clone(real)); const v = db.vehicles[0];
  v.purchase = { date: '2020-05-01', price: 28000, odometer: 120000, seller: 'Private', notes: '' };
  db.odometerLogs.push({ id: 'l1', vehicleId: v.id, date: '2026-07-20', odometer: 236950 }); // same day as a service, higher
  const r = C.odometerReadings(db, v);
  assert.strictEqual(r[0].src, 'purchase');
  assert.strictEqual(r.filter(x => x.date === '2026-07-20').length, 1);
  assert.strictEqual(r.find(x => x.date === '2026-07-20').odo, 236950);
});
test('F-02 build sheet sync keeps user fields and drops unticked parts', () => {
  const db = C.migrate({ schemaVersion: 1, vehicles: [{ id: 'v' }], services: [] });
  let n = 0; const uid = () => 'r' + (++n);
  const s = { id: 's', vehicleId: 'v', date: '2026-05-01', odometer: 1000, type: 'upgrade',
    parts: [{ id: 'p1', name: 'Bilstein 5100', partNo: '24-186', qty: 2, showOnBuild: true }, { id: 'p2', name: 'Bolts', showOnBuild: false }] };
  C.syncBuildFromService(db, s, uid, 'now');
  assert.strictEqual(db.buildSheet.length, 1);
  db.buildSheet[0].brand = 'Bilstein'; db.buildSheet[0].removedDate = '2026-10-01';
  s.date = '2026-05-02'; C.syncBuildFromService(db, s, uid, 'now');
  assert.strictEqual(db.buildSheet[0].brand, 'Bilstein'); assert.strictEqual(db.buildSheet[0].removedDate, '2026-10-01');
  assert.strictEqual(db.buildSheet[0].installedDate, '2026-05-02');
  s.parts[0].showOnBuild = false; C.syncBuildFromService(db, s, uid, 'now');
  assert.strictEqual(db.buildSheet.length, 0);
});
test('import merge adds only new ids; replace keeps device settings', () => {
  const a = C.migrate(clone(real)); a.settings.lastBackupAt = 'X';
  const b = clone(a); b.services.push({ ...b.services[0], id: 'new1' }); b.services[0].notes = 'changed'; b.settings.lastBackupAt = 'Y';
  const { data, added } = C.mergeData(a, b);
  assert.strictEqual(added.services, 1); assert.strictEqual(data.services.length, a.services.length + 1);
  assert.notStrictEqual(data.services[0].notes, 'changed');
  assert.strictEqual(C.replaceData(a, b).settings.lastBackupAt, 'X');
});

console.log(`\n${pass} passed, ${fail} failed`);
process.exit(fail ? 1 : 0);
